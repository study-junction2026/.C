#include<stdio.h>
#include<math.h>

int main(){
    int x = 4 + 9 * 10;
    printf("Value of x: %d\n", x);
    int y = 4 * 3 / 6 * 2;
    printf("Value of y: %d\n", y);

    int a = 5 * 2 - 2 * 3;
    printf("Value of a: %d\n", a);

    int b = 5 * 2 / 2 * 3;
    printf("Value of b: %d\n", b);

    int c = 5 * (2 / 2) * 3;
    printf("Value of c: %d\n", c);

    int d = 5 + 2 / 2 * 3;
    printf("Value of d: %d\n", d);
    return 0;
}